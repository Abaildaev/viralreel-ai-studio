/*
  Обращение по имени в публичном ответе.

  `{имя}` подставляется из профиля автора комментария, если оно похоже на имя:
  «Кирилл Селиверстов» → «Кирилл», а «officiant», «ylua» и «𝓐𝓭𝓪𝓶» отбрасываются
  проверкой в _shared/personalize.ts. Проверка строгая намеренно — «Привет,
  ylua» видно под постом всем.

  Плейсхолдер стоит либо первым словом, либо сразу после короткого зачина с
  запятой: только эти два места убираются чисто, когда имени не нашлось.
  «Всё, {имя}, отправил» без имени становится «Всё, отправил», а «{имя},
  готово» — «Готово». В середине фразы плейсхолдер оставил бы строчную букву
  после точки, поэтому там его нет.

  Побочная польза, ради которой это стоит и само по себе: одинаковый текст на
  четыреста отправок в неделю — один из признаков, по которым Instagram и
  прячет переписку в «Скрытые запросы». Имя делает каждый ответ разным.
*/

UPDATE lead_magnets magnet
SET
  public_reply_variants = ARRAY[
    'Всё, {имя}, отправил инфу тебе в лс 🤝 Не видишь — Instagram прячет сообщения от неподписанных: Direct → «Запросы», а если и там пусто, то в самом низу «Скрытые запросы». Или просто забирай ссылку в шапке профиля',
    '{имя}, готово — скинул в личку 🙌 Пусто в Direct — загляни в «Запросы», потом в «Скрытые запросы». Быстрее всего ссылка в шапке профиля',
    'Готово, {имя}! Улетело тебе в Direct 🚀 Не пришло — проверь «Запросы» и «Скрытые запросы», Instagram любит туда убирать. Ссылка есть и в шапке профиля',
    '{имя}, отправил 📩 Если не всплыло — оно в «Запросах» или в «Скрытых запросах». Не хочешь искать, бери ссылку в шапке профиля',
    'Всё скинул в лс, {имя} 🤝 Не нашёл — сначала «Запросы», потом «Скрытые запросы». Или сразу шапка профиля, там та же ссылка'
  ],
  updated_at = now()
WHERE magnet.id IN (
  SELECT funnel.lead_magnet_id
  FROM telegram_funnels funnel
  WHERE funnel.slug = 'prompts'
    AND funnel.lead_magnet_id IS NOT NULL
);

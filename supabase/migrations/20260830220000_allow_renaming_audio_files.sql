/*
  # Переименование аудиофайла

  У `audio_files` были политики на чтение, вставку и удаление — и не было на
  изменение. Интерфейс при этом трек переименовывает. RLS не отвергала запрос
  с ошибкой, а просто не находила ни одной строки: Supabase возвращал успех и
  ноль изменённых записей.

  Дальше становилось хуже: код проверял `error`, получал null, считал это
  успехом и оптимистично менял имя в состоянии страницы. Человек видел новое
  имя, перезагружал вкладку и получал старое.

  Ограничение то же, что у остальных трёх политик: строка принадлежит
  вызывающему. `WITH CHECK` дописан отдельно, чтобы переименование нельзя было
  использовать для передачи файла другому пользователю.
*/

DROP POLICY IF EXISTS "Users can update own audio files" ON audio_files;
CREATE POLICY "Users can update own audio files"
  ON audio_files
  FOR UPDATE
  TO authenticated
  USING (auth.uid() = user_id)
  WITH CHECK (auth.uid() = user_id);

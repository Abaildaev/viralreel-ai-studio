/*
  # Текст чипса не показывает пальцем вниз

  «Нажми кнопку ниже» — верно для кнопки внутри сообщения и неверно для
  quick reply: чипс отрисовывается над полем ввода, а не под текстом. Человек
  идёт взглядом туда, куда показывает стрелка, ничего там не находит и
  считает, что сообщение не дошло. Один так и написал в ответ: «Не вижу
  вашего сообщения ;(».

  Направление убрано, кнопка названа по имени — искать «Забрать базу» можно
  где угодно на экране, а «ниже» работает только в одном месте.
*/

UPDATE lead_magnets magnet
SET
  ab_quick_reply_text =
    'Готово 🙌 База из 1000+ промптов уже ждёт. Нажми кнопку «' ||
    coalesce(nullif(btrim(magnet.ab_quick_reply_button), ''), 'Забрать базу') ||
    '» — и я сразу пришлю доступ.',
  updated_at = now()
WHERE magnet.id IN (
  SELECT funnel.lead_magnet_id
  FROM telegram_funnels funnel
  WHERE funnel.slug = 'prompts'
    AND funnel.lead_magnet_id IS NOT NULL
);

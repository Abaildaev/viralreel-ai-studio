/*
  # Персональный текст первого сообщения в Direct

  Пять заготовленных вариантов расходятся на четыреста доставок в неделю — то
  есть каждый текст уходит примерно восемьдесят раз слово в слово. Instagram
  прячет такие переписки в «Скрытые запросы», и это видно по доходимости: до
  Telegram добирается около десятой части получателей.

  1. Изменения
    - `lead_magnets.direct_ai_personalize` (boolean, по умолчанию false) —
      писать ли текст моделью под каждого человека.

  2. Как это работает
    Модель переписывает только текст сообщения. Кнопка, ссылка и вложение
    собираются прежним кодом и не меняются, а любая осечка — нет ключа,
    таймаут, ссылка в ответе вопреки запрету — молча возвращает заготовленный
    вариант. Доставка не зависит от того, ответила ли модель.

  3. Почему выключено по умолчанию
    Каждая доставка становится обращением к платному API от имени владельца
    ключа. Такое включают осознанно, как и самого ИИ-продавца.
*/

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'lead_magnets'
      AND column_name = 'direct_ai_personalize'
  ) THEN
    ALTER TABLE public.lead_magnets
      ADD COLUMN direct_ai_personalize boolean NOT NULL DEFAULT false;
  END IF;
END $$;

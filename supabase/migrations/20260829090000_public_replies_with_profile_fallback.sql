UPDATE lead_magnets magnet
SET
  public_reply_variants = ARRAY[
    'Всё, бро, отправил инфу тебе в лс 🤝 Не пришло — глянь вкладку «Запросы» в Direct, туда Instagram кладёт сообщения от неподписанных. Или забирай ссылку в шапке профиля',
    'Готово, скинул в личку 🙌 Пусто во «Входящих» — проверь «Запросы», а если лень искать, ссылка лежит у меня в шапке профиля',
    'Улетело тебе в Direct 🚀 Не видишь — загляни в «Запросы». Там же всё есть в шапке профиля, если так быстрее',
    'Отправил 📩 Если сообщение не всплыло — оно ждёт во вкладке «Запросы». Или бери ссылку в шапке профиля, это тот же материал',
    'Всё скинул в лс 🤝 Не нашёл — вкладка «Запросы» в Direct или шапка профиля, там та же ссылка'
  ],
  updated_at = now()
WHERE magnet.id IN (
  SELECT funnel.lead_magnet_id
  FROM telegram_funnels funnel
  WHERE funnel.slug = 'prompts'
    AND funnel.lead_magnet_id IS NOT NULL
);

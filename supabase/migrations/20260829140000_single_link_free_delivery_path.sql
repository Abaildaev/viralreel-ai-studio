/*
  # Одна доставка вместо трёх, и без ссылки в первом сообщении

  Владелец нашёл свои сообщения в «Скрытых запросах» Instagram. Причина видна
  в самой доставке: ссылка на t.me уходила в первом же сообщении человеку, не
  подписанному на аккаунт, через пять секунд после комментария, четыреста раз
  в неделю.

  1. Что меняется
    - `ab_quick_reply_percent` и `ab_profile_reply_percent` → 0. Оба
      экспериментальных плеча выключены.
    - `direct_ai_personalize` → true. Теперь весь трафик идёт одним путём:
      текст пишет модель под конкретного человека, первое сообщение уходит
      БЕЗ ссылки, адрес выдаётся после нажатия кнопки.
    - В `keywords` добавлены опечатки, на которых терялись живые лиды.

  2. Почему убран вариант со ссылкой сразу
    Это и был `control`. При нулевых процентах он выбирается по-прежнему, но
    `direct_ai_personalize` переводит его в форму quick reply, так что ссылки
    в первом сообщении не остаётся ни у кого. Если ИИ когда-нибудь выключат,
    прежнее поведение вернётся само.

    `profile_link` выключен по результату: 0 переходов в Telegram из 30
    отправок. Он звал искать ссылку в шапке профиля, и никто не пошёл.

  3. Про новые ключевые слова
    За неделю мимо кодового слова прошли 34 человека. Замер по журналу:
    «прост» ловит 29 комментариев, из них 5 длинных — это спам конкурентов,
    он получит Direct впустую. Двадцать четыре живых лида того стоят.
    «пром» ловит 19 и одним словом покрывает «промт», «промп» и «промнт»; за
    ту же неделю он не поймал ни одного длинного комментария, то есть «промо»
    и «промокод» этой аудиторией не пишутся. «promt» — латиница, которую
    «prompt» не покрывает: это разные строки.
*/

UPDATE lead_magnets magnet
SET
  ab_quick_reply_percent = 0,
  ab_profile_reply_percent = 0,
  direct_ai_personalize = true,
  keywords = ARRAY[
    'промпт', 'промт', 'пром', 'прост', 'промнт',
    'prompt', 'promt', 'ghjvgn', 'ghjvn'
  ],
  updated_at = now()
WHERE magnet.id IN (
  SELECT funnel.lead_magnet_id
  FROM telegram_funnels funnel
  WHERE funnel.slug = 'prompts'
    AND funnel.lead_magnet_id IS NOT NULL
);

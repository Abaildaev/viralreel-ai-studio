/*
  Публичный ответ называет «Скрытые запросы».

  Владелец аккаунта нашёл переписку не во «Входящих» и не в «Запросах», а в
  «Скрытых запросах» — папке, куда Instagram убирает то, что счёл спамом.
  Прежний совет «загляни в Запросы» вёл не туда: он называл папку, в которой
  сообщения нет.

  Разница между двумя папками для человека огромная. «Запросы» видны сразу под
  Direct, а «Скрытые запросы» лежат в самом низу их списка, и большинство
  людей не знает об их существовании. Совет, который не называет путь целиком,
  бесполезен ровно так же, как отсутствие совета.

  Порядок в тексте — от частого к редкому: «Запросы», потом «Скрытые запросы»,
  потом шапка профиля как путь, не зависящий от Direct вообще.
*/

UPDATE lead_magnets magnet
SET
  public_reply_variants = ARRAY[
    'Всё, бро, отправил инфу тебе в лс 🤝 Не видишь — Instagram прячет сообщения от неподписанных: Direct → «Запросы», а если и там пусто, то в самом низу «Скрытые запросы». Или просто забирай ссылку в шапке профиля',
    'Готово, скинул в личку 🙌 Пусто в Direct — загляни в «Запросы», потом в «Скрытые запросы». Быстрее всего — ссылка в шапке профиля',
    'Улетело тебе в Direct 🚀 Не пришло — проверь «Запросы» и «Скрытые запросы», Instagram любит туда убирать. Ссылка есть и в шапке профиля',
    'Отправил 📩 Если не всплыло — оно в «Запросах» или в «Скрытых запросах». Не хочешь искать — бери ссылку в шапке профиля',
    'Всё скинул в лс 🤝 Не нашёл — сначала «Запросы», потом «Скрытые запросы». Или сразу шапка профиля, там та же ссылка'
  ],
  updated_at = now()
WHERE magnet.id IN (
  SELECT funnel.lead_magnet_id
  FROM telegram_funnels funnel
  WHERE funnel.slug = 'prompts'
    AND funnel.lead_magnet_id IS NOT NULL
);

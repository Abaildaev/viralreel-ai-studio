/*
  # Три варианта выдачи одновременно, по трети трафика

  Прежние сравнения этих плеч не стоили бумаги: контроль работал 27–28
  августа, когда публичные ответы были выключены и вся воронка лежала на
  18–24%, а Quick Reply набрал свой объём 29–30-го, уже после починки.
  Панель делила одно на другое и показывала Quick Reply победителем, хотя
  на общих днях он был позади. Теперь все три идут бок о бок, и сравнение
  наконец честное.

  1. Что включается
    - `ab_quick_reply_percent` = 33 → чипс с шаблонным текстом.
    - `ab_profile_reply_percent` = 33 → сообщение «ссылка в шапке профиля».
    - Остаток, 34% → контроль: текст из списка и кнопка со ссылкой сразу.

  2. Почему выключается direct_ai_personalize
    Он перехватывает именно контрольное плечо и превращает его в чипс с
    текстом от модели. С включённым флагом контроля не существует, и
    сравнивать было бы нечего.

  3. Чего этот тест не измерит
    `profile_link` отправляет человека по ссылке из шапки, а она одна на
    всех и метки события не несёт. Такой подписчик приходит без
    привязки к событию, поэтому конверсия плеча в его собственных цифрах
    будет занижена — почти наверняка близка к нулю, как и раньше. Читать
    его придётся косвенно: по общему числу приходов «без метки» за день,
    сопоставляя с объёмом плеча. Чтобы мерить прямо, нужна отдельная метка
    в ссылке из шапки — этого пока нет.
*/

UPDATE lead_magnets magnet
SET
  ab_quick_reply_percent = 33,
  ab_profile_reply_percent = 33,
  direct_ai_personalize = false,
  updated_at = now()
WHERE magnet.id IN (
  SELECT funnel.lead_magnet_id
  FROM telegram_funnels funnel
  WHERE funnel.slug = 'prompts'
    AND funnel.lead_magnet_id IS NOT NULL
);
